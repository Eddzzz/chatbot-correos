async page => {
  const check=(ok,message)=>{if(!ok)throw Error(message);};
  const id='11111111-1111-1111-1111-111111111111';
  let sent;
  await page.setViewportSize({width:1100,height:850});
  await page.context().grantPermissions(['clipboard-read','clipboard-write'],{origin:'http://127.0.0.1:5174'});
  const history=[{role:'user',content:'Carga de agosto de 2026'},{role:'assistant',content:'Resumen de agosto',status:'answer'},{role:'user',content:'septiembre de 2026'},{role:'assistant',content:'Resumen de septiembre',status:'answer'}];
  await page.route('**/api/config',r=>r.fulfill({json:{data_mode:'demo'}}));
  await page.route('**/api/sessions',r=>r.fulfill({json:{sessions:[{session_id:id,title:'Carga postal'}]}}));
  await page.route(`**/api/sessions/${id}`,r=>r.fulfill({json:{messages:history}}));
  await page.route('**/api/chat/stream',async r=>{
    sent=r.request().postDataJSON();
    const completed={request_id:'edit-test',session_id:id,status:'answer',answer:'Carga de agosto por departamentos'};
    await r.fulfill({contentType:'text/event-stream',body:`event: request_started\ndata: ${JSON.stringify({request_id:'edit-test',session_id:id})}\n\nevent: completed\ndata: ${JSON.stringify(completed)}\n\n`});
  });
  await page.goto(`http://127.0.0.1:5174/c/${id}`);
  await page.getByLabel('Clave de acceso',{exact:true}).fill('ui-test');
  await page.getByRole('button',{name:'Iniciar conversación'}).click();
  const edit=page.getByRole('button',{name:'Editar consulta',exact:true});
  const bubble=page.locator('.message.user').last();
  await page.mouse.move(0,0);
  check(await bubble.locator('.message-actions').evaluate(el=>getComputedStyle(el).opacity)==='0','Actions visible before hover');
  const dimensions=await bubble.locator('.message-text').evaluate(el=>({height:el.getBoundingClientRect().height,radius:getComputedStyle(el).borderRadius}));
  check(dimensions.height<=44 && dimensions.radius==='24px','Bubble is not compact and rounded');
  await bubble.hover();
  check(await bubble.locator('.message-actions').evaluate(el=>getComputedStyle(el).opacity)==='1','Actions missing on hover');
  await bubble.getByRole('button',{name:'Copiar consulta',exact:true}).click();
  check(await page.evaluate(()=>navigator.clipboard.readText())==='septiembre de 2026','Copy changed query text');
  await bubble.getByRole('button',{name:'Consulta copiada',exact:true}).waitFor();
  check(await edit.first().textContent()==='','Edit action has visible text');
  check(await edit.first().locator('svg').count()===1,'Pencil icon missing');
  await edit.last().click();
  const field=page.getByRole('textbox',{name:'Editar consulta',exact:true});
  check(await page.locator('.message-edit button').allTextContents().then(labels=>labels.every(label=>!label.trim())),'Editor actions have visible text');
  check(await page.locator('.message-edit label,.message-edit small').count()===0,'Editor contains visible instructions');
  check(await field.inputValue()==='septiembre de 2026','Wrong original query');
  check(await field.evaluate(el=>el===document.activeElement),'Editor not focused');
  await field.fill('por departamentos');
  await page.getByRole('button',{name:'Cancelar edición',exact:true}).click();
  check(await page.getByText('Resumen de septiembre',{exact:true}).count()===1,'Cancel altered history');
  await bubble.hover();
  await edit.last().click();
  await field.fill('por departamentos');
  await page.getByRole('button',{name:'Guardar y reenviar',exact:true}).click();
  await page.getByText('Carga de agosto por departamentos',{exact:true}).waitFor();
  check(sent.session_id===id && sent.edit_message_index===2 && sent.message==='por departamentos','Wrong edit payload');
  check(await page.getByText('Resumen de septiembre',{exact:true}).count()===0,'Old answer remains');
  check(await page.getByText('Resumen de agosto',{exact:true}).count()===1,'Prior context removed');
  await page.locator('.message.user').first().hover();
  await page.screenshot({path:'output/playwright/query-hover-desktop.png'});
  await edit.first().click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'output/playwright/query-edit-mobile.png'});
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile overflow');
  await field.press('Escape');
  check(await field.count()===0,'Escape did not cancel');
  return 'PASS: hover actions, clipboard, compact round bubbles, icon-only editor, cancel, resend, mobile and Escape.';
}
